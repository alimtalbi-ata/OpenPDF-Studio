"""Version-aware, fail-closed Inno Setup recipe for the Windows release.

The Windows one-command build calls this before source preflight. The recipe
is deterministic and deliberately refuses to overwrite hand-edited recipes.
It does not install software, invoke a shell, or claim Windows qualification.

Author: Abdelhalim Talbi. OpenPDF Studio V49.1.
"""
from __future__ import annotations

import argparse
import os
from pathlib import Path
import re
import tempfile

VERSION_PATTERN = re.compile(r"[0-9]{1,4}\.[0-9]{1,4}\Z", re.ASCII)
RECIPE_NAME = "OpenPDF-Studio-V{version}.iss"


def render_recipe(version: str) -> str:
    """Render fixed Inno Setup instructions with a validated version token."""
    if not isinstance(version, str) or not VERSION_PATTERN.fullmatch(version):
        raise ValueError("Invalid release version for Inno Setup")
    return f'''#define AppName "OpenPDF Studio"
#define AppVersion "{version}"
; Generated by openpdf_inno_recipe_v491.py; edit the generator, not this file.
[Setup]
AppId={{{{A94653C4-3C6E-4B8D-BF1C-728A7EDB1C2A}}
AppName={{#AppName}}
AppVersion={{#AppVersion}}
AppPublisher=Abdelhalim Talbi
DefaultDirName={{autopf}}\\OpenPDF Studio
DefaultGroupName=OpenPDF Studio
OutputDir=..\\01-Application\\binary\\.staging-v{version}
OutputBaseFilename=OpenPDF-Studio-V{version}-Setup
Compression=lzma2
SolidCompression=yes
WizardStyle=modern
ArchitecturesAllowed=x64compatible
ArchitecturesInstallIn64BitMode=x64compatible
UninstallDisplayIcon={{app}}\\OpenPDF-Studio.exe
[Files]
Source: "dist\\OpenPDF-Studio\\*"; DestDir: "{{app}}"; Flags: recursesubdirs createallsubdirs ignoreversion
[Icons]
Name: "{{group}}\\OpenPDF Studio"; Filename: "{{app}}\\OpenPDF-Studio.exe"
Name: "{{autodesktop}}\\OpenPDF Studio"; Filename: "{{app}}\\OpenPDF-Studio.exe"; Tasks: desktopicon
[Tasks]
Name: desktopicon; Description: "Creer un raccourci sur le bureau"; GroupDescription: "Raccourcis :"
[Run]
Filename: "{{app}}\\OpenPDF-Studio.exe"; Description: "Lancer OpenPDF Studio"; Flags: nowait postinstall skipifsilent
'''


def ensure_recipe(root: Path, version: str | None = None) -> Path:
    """Create a missing recipe atomically, reject any conflicting existing file."""
    root = Path(root).resolve(strict=True)
    sources = root / "03-Sources"
    if not sources.is_dir() or sources.is_symlink():
        raise ValueError("Invalid source directory")
    declared = (root / "VERSION.txt").read_text(encoding="utf-8-sig").strip()
    if version is not None and version != declared:
        raise ValueError("Requested version differs from VERSION.txt")
    content = render_recipe(declared)
    destination = sources / RECIPE_NAME.format(version=declared)
    if destination.is_symlink():
        raise ValueError("Refusing a symlink recipe")
    if destination.exists():
        if not destination.is_file() or destination.read_bytes() != content.encode("utf-8"):
            raise ValueError("Existing Inno Setup recipe differs; refusing overwrite")
        return destination
    fd, temp_name = tempfile.mkstemp(prefix=".openpdf-inno-", suffix=".tmp", dir=sources)
    try:
        with os.fdopen(fd, "wb") as stream:
            stream.write(content.encode("utf-8"))
            stream.flush()
            os.fsync(stream.fileno())
        # Refuse overwriting a concurrent recipe; this is an exclusive creation.
        try:
            os.link(temp_name, destination)
        except FileExistsError:
            if destination.is_symlink() or destination.read_bytes() != content.encode("utf-8"):
                raise ValueError("Concurrent recipe differs; refusing overwrite")
        except OSError:
            # Windows filesystems can deny hardlinks. Exclusive create still
            # prevents replacing a pre-existing user file.
            try:
                with destination.open("xb") as out:
                    out.write(content.encode("utf-8"))
            except FileExistsError:
                if destination.is_symlink() or destination.read_bytes() != content.encode("utf-8"):
                    raise ValueError("Concurrent recipe differs; refusing overwrite")
        return destination
    finally:
        Path(temp_name).unlink(missing_ok=True)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate/verify a versioned Inno Setup recipe")
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[1])
    parser.add_argument("--version", default=None)
    args = parser.parse_args()
    print(ensure_recipe(args.root, args.version))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
